import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { configureRuntimePaths } from '../backend/runtimePaths.ts';
import { validateGroupParticipantConfigs } from '../src/data/groupParticipants.ts';
import { hasGroupMention, resolveGroupTargets } from '../src/data/groupChat.ts';
import { buildRoomSyncPrompt, buildCodexRoomChatPrompt } from '../backend/groupChat.ts';
import type { GroupParticipant, GroupParticipantConfig, SessionRecord } from '../src/data/types.ts';

const config: GroupParticipantConfig = { id: 'reviewer', label: '审查', provider: 'codex', enabled: true, model: 'future-model', effort: 'ultra', instructions: 'Review changes without editing.' };
const member: GroupParticipant = { ...config, backingSessionId: 'member', lastAppliedRoomSeq: 0 };
assert.deepEqual(resolveGroupTargets('请@reviewer检查', [member], []), ['reviewer']);
assert.deepEqual(resolveGroupTargets('@unknown 检查', [member], []), []);
assert.deepEqual(resolveGroupTargets('@reviewer-2 检查', [member], []), []);
assert.equal(hasGroupMention('请 @reviewer 检查'), false, 'Unknown standalone mentions must not convert ordinary chats');
assert.equal(hasGroupMention('请@codex检查'), true);
assert.deepEqual(resolveGroupTargets('继续', [member], [{ id: 'reply', role: 'assistant', timestamp: '', title: '', content: 'done', speakerId: member.id, status: 'complete' }]), ['reviewer']);
console.log('PASS custom handles route by stable identity, including Chinese-adjacent mentions');

assert.deepEqual(validateGroupParticipantConfigs([config])[0], config);
assert.equal(validateGroupParticipantConfigs([{ ...config, effort: undefined }])[0].effort, 'default');
assert.throws(() => validateGroupParticipantConfigs([config, config]), /唯一/);
assert.throws(() => validateGroupParticipantConfigs([{ ...config, id: 'all' }]), /标识/);
assert.throws(() => validateGroupParticipantConfigs([{ ...config, enabled: false }]), /至少启用/);
assert.throws(() => validateGroupParticipantConfigs([{ ...config, instructions: 'x'.repeat(8001) }]), /过长/);
console.log('PASS participant configuration rejects ambiguous and invalid membership');

await mkdir('.tmp-tests', { recursive: true });
const root = await mkdtemp(path.resolve('.tmp-tests', 'group-members-'));
const data = path.join(root, 'data');
const home = path.join(root, 'home');
const workspace = path.join(root, 'workspace');
await Promise.all([data, home, workspace].map((directory) => mkdir(directory)));
await writeFile(path.join(data, 'easyaiflow-sessions.json'), JSON.stringify({ projects: [], deletedImports: { claudeSessionIds: [], codexThreadIds: [] } }));
configureRuntimePaths({ mode: 'web', userDataPath: data, homePath: home });
const fresh = () => import(`${pathToFileURL(path.resolve('electron/sessionStore.ts')).href}?group=${Math.random()}`);
let store = await fresh();
const project = await store.createProject('Members', workspace);
const created = await store.createSessionInStreamwork(project.session.dreamId, 'Team', false, 'claude', 'group');
const initial = created.session.group.kind === 'room' ? created.session.group.participants : [];
const saved = await store.configureGroupParticipants(created.session.id, 0, [...initial, config], true);
assert.equal(saved.session.group?.configurationRevision, 1);
assert.equal(saved.session.group?.collaborationEnabled, true);
const members = saved.session.group.participants as GroupParticipant[];
assert.equal(members.length, 3);
assert.equal(new Set(members.map((entry) => entry.backingSessionId)).size, 3);
assert.equal(members.filter((entry) => entry.provider === 'codex').length, 2);
await assert.rejects(store.configureGroupParticipants(created.session.id, 0, members), /其他窗口/);
await assert.rejects(store.configureGroupParticipants(created.session.id, 1, members.filter((entry) => entry.id !== 'claude')), /停用/);
await assert.rejects(store.configureGroupParticipants(created.session.id, 1, members.map((entry) => entry.id === 'reviewer' ? { ...entry, provider: 'claude' } : entry)), /不能更换/);
const reviewer = members.find((entry) => entry.id === 'reviewer')!;
const prompts = [buildRoomSyncPrompt(saved.session as SessionRecord, reviewer, [], 0), buildCodexRoomChatPrompt(reviewer, [])];
assert.ok(prompts.every((prompt) => prompt.includes('@reviewer') && prompt.includes(config.instructions!)));
console.log('PASS multiple same-provider members have separate sessions and independent role prompts');

await store.configureGroupParticipants(created.session.id, 1, members.map((entry) => ({ ...entry, enabled: entry.id !== 'codex' })));
await store.appendMessagesToSession(created.session.id, [{ id: 'kept-message', role: 'assistant', timestamp: 'now', title: 'Reviewed', content: 'Preserve my identity', speakerId: 'reviewer', speakerLabel: '审查', status: 'complete' }], 'done', 'now');
await store.flushPendingSave();
store = await fresh();
const reopened = await store.getSessionRecordForBootstrap(created.session.id);
assert.equal(reopened.group.configurationRevision, 2);
assert.equal(reopened.group.collaborationEnabled, true);
assert.deepEqual(reopened.group.participants.map((entry: GroupParticipant) => [entry.id, entry.backingSessionId, entry.model, entry.effort, entry.instructions]), members.map((entry) => [entry.id, entry.backingSessionId, entry.model, entry.effort, entry.instructions]));
assert.equal(reopened.group.participants.find((entry: GroupParticipant) => entry.id === 'codex').enabled, false);
assert.deepEqual(reopened.messages.map((message: { id: string }) => message.id), ['kept-message']);
await store.getProjectsForBootstrap();
const ensured = await store.ensureGroupRoomBackingSessions(created.session.id);
assert.equal(ensured.group.participants.length, 3);
assert.equal(ensured.group.configurationRevision, 2);
assert.equal((await store.findSession(reviewer.backingSessionId)).group.speakerLabel, '审查');
console.log('PASS custom membership, models, effort, roles and message IDs survive refresh and store restart');
await store.flushPendingSave();

const placed = { id: 'remote', label: 'Remote', provider: 'claude', enabled: true, placement: { deviceId: 'AAAAAAAA-BBBB-CCCC-DDDD-EEEEEEEEEEEE', projectId: 'project-1' } };
assert.deepEqual(validateGroupParticipantConfigs([placed])[0].placement, { deviceId: 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee', projectId: 'project-1' });
for (const placement of [{ deviceId: 'local', projectId: 'p' }, { deviceId: placed.placement.deviceId, projectId: '' }, 'device']) {
  assert.throws(() => validateGroupParticipantConfigs([{ ...placed, placement }]), /执行设备或项目无效/);
}
const unresolved = [...reopened.group.participants.map(({ id, label, provider, enabled }: GroupParticipant) => ({ id, label, provider, enabled })), placed];
await assert.rejects(store.configureGroupParticipants(created.session.id, 2, unresolved), /尚未在执行设备上创建/);
await assert.rejects(store.configureGroupParticipants(created.session.id, 2, unresolved.map((entry: { id: string }) => entry.id === 'reviewer' ? { ...entry, placement: placed.placement } : entry)), /执行设备不能更换/);
const remote = { ...placed.placement, deviceId: 'aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee', sessionId: 'executor-session', workspace: 'D:/remote', deviceName: 'Laptop' };
const withRemote = await store.configureGroupParticipants(created.session.id, 2, validateGroupParticipantConfigs(unresolved), undefined, new Map([['remote', remote]]));
const stored = withRemote.session.group.participants.find((entry: GroupParticipant) => entry.id === 'remote');
assert.deepEqual(stored.remote, remote);
assert.equal('placement' in stored, false);
console.log('PASS remote placements are validated, require an executor session and cannot move existing members');
await store.flushPendingSave();
